-- CREATE OR REPLACE, no IF NOT EXISTS: fuerza el esquema aquí definido aunque ya exista una DIM_CLUB previa con columnas distintas.
CREATE OR REPLACE TABLE FOOTBALL.GOLD.DIM_CLUB (
  CLUB_ID                   NUMBER        NOT NULL,
  CLUB_CODE                 STRING,
  CLUB_NAME                 STRING,
  DOMESTIC_COMPETITION_ID   STRING,
  STADIUM_NAME              STRING,
  STADIUM_SEATS             NUMBER,
  SQUAD_SIZE                NUMBER,
  AVERAGE_AGE               NUMBER(10,2),
  FOREIGNERS_NUMBER         NUMBER,
  FOREIGNERS_PERCENTAGE     NUMBER(10,2),
  NATIONAL_TEAM_PLAYERS     NUMBER,
  COACH_NAME                STRING,
  LAST_SEASON               NUMBER,
  TOTAL_MARKET_VALUE        NUMBER,
  NET_TRANSFER_RECORD       STRING,
  URL                       STRING,
  PRIMARY KEY (CLUB_ID)
);

